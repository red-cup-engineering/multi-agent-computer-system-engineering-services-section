import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {createHash} from 'node:crypto';
const journalDir=path.dirname(path.dirname(fs.readFileSync('/tmp/muse-segment-path','utf8').trim()));
const eventPath=path.join(journalDir,'event.mjs');
const identityPath=path.join(journalDir,'../identity/index.mjs');
const {addressUniqueJournalCommand,uniqueJournalRecord,parseUniqueJournalRecord}=await import(pathToFileURL(eventPath));
const {addressArtifact,verifyArtifact}=await import(pathToFileURL(identityPath));
const command={kind:'metroplat.journal.unique-command',version:1,domain:'interaction',key:{context:'fixture-context',principal:'fixture-person',requestId:'same-request'},subject:'fixture-person',value:{kind:'message',text:'Prepare a sourced comparison.'},causes:[],artifactRefs:[]};
const journal='fixture-journal';
const addressed=addressUniqueJournalCommand(command,journal);
const record=uniqueJournalRecord(command,{journal,seat:command.key.principal,admittedAt:'2026-09-27T12:00:00.000Z',artifacts:[]});
const parsed=parseUniqueJournalRecord(record,journal,addressed.slotDigest);
const body=addressArtifact(parsed.command);
const listed=new Map([...record.witness.sources,...record.artifacts].map(x=>[x.ref,x.canonicalText]));
assert.equal(listed.has(parsed.reference.payload),false);
assert.equal(body.ref,record.commandRef);
assert.equal(body.ref,parsed.reference.payload);
assert.equal(verifyArtifact(body.ref,body.canonical.text).canonical.text,body.canonical.text);
assert.deepEqual(JSON.parse(body.canonical.text),command);
console.log(JSON.stringify({method:'Existing unique-record constructor and parser; verified command body recovered from parsed record',source:{path:eventPath,sha256:createHash('sha256').update(fs.readFileSync(eventPath)).digest('hex')},findings:{payloadNotInListedSourcePairs:!listed.has(parsed.reference.payload),parsedCommandAddressesToReturnedPayload:true,bodyIndependentlyVerified:true,commandRoundTrip:true},measurements:{listedSourcePairs:listed.size,commandCanonicalBytes:body.canonical.byteLength},limits:['No source owner, filesystem durability, domain authority or assistant workflow exercised.']},null,2));
