#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, writeFileSync, renameSync, unlinkSync } from "node:fs";
import { registerHooks } from "node:module";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const modules = [
  "inducing", "realization", "positing", "markdown", "lsp", "offices", "world", "claude-harness", "codex-harness", "lean",
  "integrations/filesystem", "markdown-files", "arc42-sad", "specifications", "claude-fleet", "claude-sessions", "agent-coordination", "claim-sessions", "codex-sessions", "openai-pricing",
  "ledger", "ledger-maintenance", "energy-accounting", "marsh", "marsh-hive-engine", "agent-token-usage", "work-coordination", "proof-health",
  "attention-allocation", "kalshi", "hive-curation", "polymarket", "hive-games", "land-contracts", "structural-claims", "heir-search", "us-representation", "enterprise",
  "run-causal-set", "session-presence", "learning", "directory-readout", "file-census", "lexicon-census", "term-catalog", "eavt-cell", "capability-assertions", "legibility",
  "module-cohesion", "module-topology", "source-code-policy", "checkout-health", "path-corpus", "archive", "proof-play", "schema-conformance", "term-intension",
  "workspace-git", "workspace-graph", "workspace-readout", "duty-worktree",
].map((name) => `@red-cup-engineering/metroplat/${name}`);

const here = path.dirname(fileURLToPath(import.meta.url));
const output = path.resolve(here, "../src/generated/operation-family-descriptors.mjs");
// Owners import this artifact while constructing declarations. Supply an empty
// module only inside this constructor; the held source file is never a scratch
// buffer, including on --check, concurrent construction or process failure.
const check = process.argv.includes("--check");
const seed = "export const operationFamilyDescriptors = {};\n";
const held = existsSync(output) ? readFileSync(output, "utf8") : undefined;
const outputUrl = pathToFileURL(output).href;
const hook = registerHooks({
  resolve(specifier, context, nextResolve) {
    if ((specifier.startsWith('.') || specifier.startsWith('file:')) && context.parentURL
        && new URL(specifier, context.parentURL).href === outputUrl) return { url: outputUrl, shortCircuit: true };
    return nextResolve(specifier, context);
  },
  load(url, context, nextLoad) {
    return url === outputUrl ? { format: 'module', source: seed, shortCircuit: true } : nextLoad(url, context);
  },
});
try {
const { defaultFilesystemBinding } = await import("@red-cup-engineering/computer-system-engine/rpc/binding");
const { lazyOperation, operationDescriptor } = await import("@red-cup-engineering/computer-system-engine/rpc/operation");
const { loadOperationFamily } = await import("../src/operation-family-loaders.mjs");
const inertEnvironment = Object.freeze(Object.create(null));
const families = {};
let operations = Object.freeze([]);
let sources = Object.freeze([]);
function declarationBinding(family) {
  const root = "/declaration-only";
  const native = defaultFilesystemBinding(`${root}/data`, {
    claudeSessionRoot: `${root}/claude-sessions`,
    codexSessionRoot: `${root}/codex-sessions`,
    codexMemoryRoot: `${root}/codex-memory`,
    packageRoot: `${root}/package`,
  });
  // Discover ports from their native carrier rather than maintaining a second interface list.
  return Object.freeze({
    ...Object.fromEntries(Object.entries(native).map(([port, value]) => [port,
      typeof value === "function"
        ? () => { throw new Error(`Declaration construction for ${family} attempted operational port ${port}`); }
        : value,
    ])),
    agencyRoot: `${root}/agency`,
  });
}
for (const module of modules) {
  const binding = declarationBinding(module);
  const family = Object.freeze(await loadOperationFamily(module, binding, { operationSource: () => operations, sourceSet: () => sources, environment: inertEnvironment }));
  families[module] = family.map((value) => operationDescriptor(lazyOperation(operationDescriptor(value), () => family)));
  sources = Object.freeze([...sources, Object.freeze({ module, operations: family })]);
  operations = Object.freeze(sources.flatMap((source) => source.operations));
}
const generated = `// Generated by scripts/generate-operation-family-descriptors.mjs; do not edit.\nexport const operationFamilyDescriptors = ${JSON.stringify(families, null, 2)};\n`;
if ((existsSync(output) ? readFileSync(output, 'utf8') : undefined) !== held) throw new Error("operation descriptor output changed during fabrication");
if (check) {
  if (held !== generated) {
    process.stderr.write("operation family descriptors differ from their owning implementations\n");
    process.exitCode = 1;
  }
} else {
  const staged = `${output}.generation-${process.pid}`;
  mkdirSync(path.dirname(output), { recursive: true });
  try { writeFileSync(staged, generated, { flag: "wx" }); renameSync(staged, output); }
  finally { if (existsSync(staged)) unlinkSync(staged); }
}
} finally {
  hook.deregister();
}
